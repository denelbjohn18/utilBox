import Foundation

enum Limits {
    static let maxTextBytes = 1_000_000
    static let maxRichBytes = 2_000_000
    static let maxImageBytes = 20 * 1024 * 1024
    static let maxFiles = 100
    static let maxUnpinned = 100
    static let maxPinned = 50
}

enum Log {
    static func error(_ message: String) {
        FileHandle.standardError.write(Data((message + "\n").utf8))
    }
}

struct TextBody: Equatable, Codable {
    var string: String
    var rtfFile: String?
    var htmlFile: String?
}

struct ImageBody: Equatable, Codable {
    var file: String
    var width: Int
    var height: Int
    var sha256: String
}

struct FileBody: Equatable, Codable {
    var paths: [String]
}

enum ClipKind: Equatable, Codable {
    case text(TextBody)
    case image(ImageBody)
    case files(FileBody)
}

struct ClipItem: Equatable, Identifiable, Codable {
    var id: UUID
    var createdAt: Date
    var pinned: Bool
    var sourceApp: String?
    var kind: ClipKind

    var isDisplayable: Bool {
        switch kind {
        case .text(let body):
            return !body.string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        case .image(let body):
            return body.width > 0 && body.height > 0 && !body.file.isEmpty && !body.sha256.isEmpty
        case .files(let body):
            return body.paths.contains { !$0.isEmpty }
        }
    }

    var blobNames: [String] {
        switch kind {
        case .text(let body):
            return [body.rtfFile, body.htmlFile].compactMap { $0 }
        case .image(let body):
            return [body.file]
        case .files:
            return []
        }
    }

    func matchesSearch(_ query: String) -> Bool {
        let needle = query.trimmingCharacters(in: .whitespacesAndNewlines)
        if needle.isEmpty { return true }
        if let sourceApp, sourceApp.localizedCaseInsensitiveContains(needle) { return true }
        switch kind {
        case .text(let body):
            return body.string.localizedCaseInsensitiveContains(needle)
        case .image(let body):
            let label = "image \(body.width)x\(body.height) \(body.width)×\(body.height)"
            return label.localizedCaseInsensitiveContains(needle)
        case .files(let body):
            return body.paths.contains { $0.localizedCaseInsensitiveContains(needle) }
        }
    }
}

struct CapturedClip: Equatable {
    var sourceApp: String?
    var payload: Payload

    enum Payload: Equatable {
        case text(string: String, rtf: Data?, html: Data?)
        case image(png: Data, width: Int, height: Int)
        case files([String])
    }
}

struct RawPaste {
    var typeNames: [String] = []
    var string: String?
    var rtf: Data?
    var html: Data?
    var filePaths: [String] = []
    var imagePNG: Data?
    var imageWidth: Int = 0
    var imageHeight: Int = 0
    var sourceApp: String?
    var rejectedOversizedText: Bool = false
}

enum ClipClassifier {
    // Community convention from nspasteboard.org. Password managers set these
    // so a history app does not keep the secret.
    static let concealed = "org.nspasteboard.ConcealedType"
    static let transient = "org.nspasteboard.TransientType"
    static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

    static func isSensitive(_ typeNames: [String]) -> Bool {
        let types = Set(typeNames)
        return types.contains(concealed) || types.contains(transient) || types.contains(autoGenerated)
    }

    static func classify(_ raw: RawPaste) -> CapturedClip? {
        if raw.rejectedOversizedText {
            if let image = validImage(raw) {
                return imageClip(image, source: raw.sourceApp)
            }
            return nil
        }
        if isSensitive(raw.typeNames) { return nil }

        let allPaths = raw.filePaths.filter { !$0.isEmpty }
        let paths = Array(allPaths.prefix(Limits.maxFiles))
        let trimmed = raw.string?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""

        if !paths.isEmpty, let string = raw.string, fileList(string, allPaths: allPaths, capped: paths) {
            return CapturedClip(sourceApp: cleanSource(raw.sourceApp), payload: .files(paths))
        }

        if let image = validImage(raw), !textWins(trimmed, imageByteCount: image.data.count) {
            return imageClip(image, source: raw.sourceApp)
        }

        if let string = raw.string, !trimmed.isEmpty {
            if string.utf8.count > Limits.maxTextBytes {
                if let image = validImage(raw) {
                    return imageClip(image, source: raw.sourceApp)
                }
                return nil
            }
            return CapturedClip(
                sourceApp: cleanSource(raw.sourceApp),
                payload: .text(string: string, rtf: capped(raw.rtf), html: capped(raw.html))
            )
        }

        if let image = validImage(raw) {
            return imageClip(image, source: raw.sourceApp)
        }
        if !paths.isEmpty {
            return CapturedClip(sourceApp: cleanSource(raw.sourceApp), payload: .files(paths))
        }
        return nil
    }

    private static func fileList(_ string: String, allPaths: [String], capped: [String]) -> Bool {
        if looksLikeFileList(string, paths: allPaths) { return true }
        if allPaths.count != capped.count && looksLikeFileList(string, paths: capped) { return true }
        return false
    }

    static func looksLikeFileList(_ string: String, paths: [String]) -> Bool {
        guard !paths.isEmpty else { return false }
        let names = paths.map { URL(fileURLWithPath: $0).lastPathComponent }
        let lines = string
            .split(whereSeparator: { $0.isNewline })
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty }
        guard lines.count == paths.count else { return false }
        if lines.count == 1 {
            let line = lines[0]
            let path = paths[0]
            if line == names[0] || line == path { return true }
            return line == URL(fileURLWithPath: path).absoluteString
        }
        let namesMatch = zip(lines, names).allSatisfy { $0 == $1 }
        let pathsMatch = zip(lines, paths).allSatisfy { $0 == $1 }
        return namesMatch || pathsMatch
    }

    static func cleanSource(_ source: String?) -> String? {
        guard let source else { return nil }
        let trimmed = source.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.isEmpty || trimmed == "utilBox" { return nil }
        if trimmed.count <= 80 { return trimmed }
        let end = trimmed.index(trimmed.startIndex, offsetBy: 80)
        return String(trimmed[..<end])
    }

    private static func textWins(_ trimmed: String, imageByteCount: Int) -> Bool {
        if trimmed.isEmpty { return false }
        if imageByteCount <= 0 { return true }
        if isURL(trimmed) { return false }
        if trimmed.count >= 24 { return true }
        return imageByteCount < 8_192
    }

    private static func isURL(_ string: String) -> Bool {
        let lower = string.lowercased()
        return lower.hasPrefix("http://") || lower.hasPrefix("https://")
    }

    private static func validImage(_ raw: RawPaste) -> (data: Data, width: Int, height: Int)? {
        guard let data = raw.imagePNG,
              !data.isEmpty,
              data.count <= Limits.maxImageBytes,
              raw.imageWidth > 0,
              raw.imageHeight > 0 else { return nil }
        return (data, raw.imageWidth, raw.imageHeight)
    }

    private static func imageClip(
        _ image: (data: Data, width: Int, height: Int),
        source: String?
    ) -> CapturedClip {
        CapturedClip(
            sourceApp: cleanSource(source),
            payload: .image(png: image.data, width: image.width, height: image.height)
        )
    }

    private static func capped(_ data: Data?) -> Data? {
        guard let data, !data.isEmpty, data.count <= Limits.maxRichBytes else { return nil }
        return data
    }
}

enum ClipDisplay {
    static func flatten(_ string: String) -> String {
        string.split(whereSeparator: { $0.isWhitespace }).joined(separator: " ")
    }

    static func title(for item: ClipItem) -> String {
        let raw: String
        switch item.kind {
        case .text(let body):
            raw = flatten(body.string)
        case .image:
            raw = "Image"
        case .files(let body):
            let paths = body.paths.filter { !$0.isEmpty }
            if paths.count == 1 {
                raw = URL(fileURLWithPath: paths[0]).lastPathComponent
            } else {
                raw = "\(paths.count) files"
            }
        }
        if raw.isEmpty { return "Clipboard item" }
        if raw.count <= 400 { return raw }
        let end = raw.index(raw.startIndex, offsetBy: 400)
        return String(raw[..<end])
    }

    static func detail(
        for item: ClipItem,
        now: Date,
        timeZone: TimeZone = .current,
        locale: Locale = .current,
        fileExists: (String) -> Bool
    ) -> String {
        var parts: [String] = []
        switch item.kind {
        case .text:
            break
        case .image(let body):
            parts.append("\(body.width)×\(body.height)")
        case .files(let body):
            let paths = body.paths.filter { !$0.isEmpty }
            if paths.count == 1, !fileExists(paths[0]) {
                parts.append("File missing")
            }
        }
        parts.append(RelativeTime.string(from: item.createdAt, now: now, timeZone: timeZone, locale: locale))
        if let source = item.sourceApp, !source.isEmpty {
            parts.append(source)
        }
        return parts.joined(separator: " · ")
    }

    static func tooltip(for item: ClipItem) -> String {
        switch item.kind {
        case .text(let body):
            let flat = flatten(body.string)
            if flat.count <= 500 { return flat }
            let end = flat.index(flat.startIndex, offsetBy: 500)
            return String(flat[..<end]) + "…"
        case .image(let body):
            return "Image, \(body.width)×\(body.height)"
        case .files(let body):
            return body.paths
                .filter { !$0.isEmpty }
                .map { URL(fileURLWithPath: $0).lastPathComponent }
                .joined(separator: "\n")
        }
    }

    static func symbolName(for item: ClipItem) -> String {
        switch item.kind {
        case .text:
            return "doc.text"
        case .image:
            return "photo"
        case .files(let body):
            return body.paths.filter { !$0.isEmpty }.count > 1 ? "doc.on.doc" : "doc"
        }
    }
}

enum RelativeTime {
    static func string(
        from date: Date,
        now: Date = Date(),
        timeZone: TimeZone = .current,
        locale: Locale = .current
    ) -> String {
        let interval = now.timeIntervalSince(date)
        if interval < 60 { return "Just now" }
        if interval < 3_600 { return "\(Int(interval / 60))m ago" }
        if interval < 86_400 { return "\(Int(interval / 3_600))h ago" }
        if interval < 7 * 86_400 { return "\(Int(interval / 86_400))d ago" }
        let formatter = DateFormatter()
        formatter.locale = locale
        formatter.timeZone = timeZone
        formatter.setLocalizedDateFormatFromTemplate("MMMd")
        return formatter.string(from: date)
    }
}

enum SHA256 {
    static func hex(_ data: Data) -> String {
        digest(Array(data)).map { String(format: "%02x", Int($0)) }.joined()
    }

    static func digest(_ message: [UInt8]) -> [UInt8] {
        var bytes = message
        let bitLength = UInt64(message.count) &* 8
        bytes.append(0x80)
        while bytes.count % 64 != 56 {
            bytes.append(0)
        }
        for shift in stride(from: 56, through: 0, by: -8) {
            bytes.append(UInt8((bitLength >> UInt64(shift)) & 0xff))
        }

        var hash: [UInt32] = [
            0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a,
            0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19
        ]

        for chunkStart in stride(from: 0, to: bytes.count, by: 64) {
            var words = [UInt32](repeating: 0, count: 64)
            for index in 0..<16 {
                let offset = chunkStart + index * 4
                words[index] = (UInt32(bytes[offset]) << 24)
                    | (UInt32(bytes[offset + 1]) << 16)
                    | (UInt32(bytes[offset + 2]) << 8)
                    | UInt32(bytes[offset + 3])
            }
            for index in 16..<64 {
                let s0 = rotate(words[index - 15], 7) ^ rotate(words[index - 15], 18) ^ (words[index - 15] >> 3)
                let s1 = rotate(words[index - 2], 17) ^ rotate(words[index - 2], 19) ^ (words[index - 2] >> 10)
                words[index] = words[index - 16] &+ s0 &+ words[index - 7] &+ s1
            }

            var a = hash[0]
            var b = hash[1]
            var c = hash[2]
            var d = hash[3]
            var e = hash[4]
            var f = hash[5]
            var g = hash[6]
            var h = hash[7]

            for index in 0..<64 {
                let s1 = rotate(e, 6) ^ rotate(e, 11) ^ rotate(e, 25)
                let choose = (e & f) ^ ((~e) & g)
                let temp1 = h &+ s1 &+ choose &+ roundConstants[index] &+ words[index]
                let s0 = rotate(a, 2) ^ rotate(a, 13) ^ rotate(a, 22)
                let majority = (a & b) ^ (a & c) ^ (b & c)
                let temp2 = s0 &+ majority
                h = g
                g = f
                f = e
                e = d &+ temp1
                d = c
                c = b
                b = a
                a = temp1 &+ temp2
            }

            hash[0] = hash[0] &+ a
            hash[1] = hash[1] &+ b
            hash[2] = hash[2] &+ c
            hash[3] = hash[3] &+ d
            hash[4] = hash[4] &+ e
            hash[5] = hash[5] &+ f
            hash[6] = hash[6] &+ g
            hash[7] = hash[7] &+ h
        }

        var output: [UInt8] = []
        output.reserveCapacity(32)
        for value in hash {
            output.append(UInt8((value >> 24) & 0xff))
            output.append(UInt8((value >> 16) & 0xff))
            output.append(UInt8((value >> 8) & 0xff))
            output.append(UInt8(value & 0xff))
        }
        return output
    }

    private static func rotate(_ value: UInt32, _ amount: UInt32) -> UInt32 {
        (value >> amount) | (value << (32 - amount))
    }

    private static let roundConstants: [UInt32] = [
        0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
        0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
        0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
        0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
        0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
        0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
        0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
        0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2
    ]
}
