final class TestLog {
    var failed = 0
    var passed = 0

    func expect(_ condition: Bool, _ message: String) {
        if condition {
            passed += 1
            return
        }
        failed += 1
        FileHandle.standardError.write(Data("FAIL \(message)\n".utf8))
    }
}

let log = TestLog()

func check(_ condition: Bool, _ message: String) {
    log.expect(condition, message)
}

func textItem(_ string: String, id: UUID = UUID(), pinned: Bool = false, at time: TimeInterval = 0, source: String? = nil) -> ClipItem {
    ClipItem(
        id: id,
        createdAt: Date(timeIntervalSince1970: time),
        pinned: pinned,
        sourceApp: source,
        kind: .text(TextBody(string: string, rtfFile: nil, htmlFile: nil))
    )
}

func textClip(_ string: String, rtf: Data? = nil, html: Data? = nil, source: String? = nil) -> CapturedClip {
    CapturedClip(sourceApp: source, payload: .text(string: string, rtf: rtf, html: html))
}

func imageClip(_ bytes: [UInt8], width: Int = 2, height: Int = 2) -> CapturedClip {
    CapturedClip(sourceApp: nil, payload: .image(png: Data(bytes), width: width, height: height))
}

func fileClip(_ paths: [String]) -> CapturedClip {
    CapturedClip(sourceApp: nil, payload: .files(paths))
}

func isPromoted(_ effect: IngestEffect, _ id: UUID) -> Bool {
    if case .promoted(let promoted) = effect { return promoted == id }
    return false
}

func testSHA256() {
    check(SHA256.hex(Data()) == "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855", "empty sha")
    check(SHA256.hex(Data("abc".utf8)) == "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad", "abc sha")
    let longer = Data("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq".utf8)
    check(
        SHA256.hex(longer) == "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1",
        "56-byte sha"
    )
}

func testClassifier() {
    check(ClipClassifier.isSensitive([ClipClassifier.concealed]), "concealed flag")
    check(ClipClassifier.isSensitive(["public.utf8-plain-text", ClipClassifier.transient]), "transient flag")
    check(ClipClassifier.isSensitive([ClipClassifier.autoGenerated]), "autogenerated flag")
    check(!ClipClassifier.isSensitive(["public.utf8-plain-text"]), "plain text is recordable")

    var secret = RawPaste()
    secret.typeNames = [ClipClassifier.concealed, "public.utf8-plain-text"]
    secret.string = "hunter2"
    check(ClipClassifier.classify(secret) == nil, "concealed text is dropped")

    var transient = RawPaste()
    transient.typeNames = [ClipClassifier.transient]
    transient.string = "one-time code"
    check(ClipClassifier.classify(transient) == nil, "transient text is dropped")

    var blank = RawPaste()
    blank.string = "   \n\t"
    check(ClipClassifier.classify(blank) == nil, "whitespace is dropped")

    var sentence = RawPaste()
    sentence.string = "Hello from the notes app today"
    sentence.rtf = Data("{\\rtf1 hi}".utf8)
    sentence.html = Data("<p>hi</p>".utf8)
    sentence.sourceApp = " Notes "
    let classified = ClipClassifier.classify(sentence)
    if case .text(let string, let rtf, let html)? = classified?.payload {
        check(string == "Hello from the notes app today", "text kept verbatim")
        check(rtf != nil && html != nil, "rich text kept")
        check(classified?.sourceApp == "Notes", "source trimmed")
    } else {
        check(false, "expected text clip")
    }

    var hugeRich = RawPaste()
    hugeRich.string = "hello"
    hugeRich.rtf = Data(count: Limits.maxRichBytes + 1)
    hugeRich.html = Data(count: Limits.maxRichBytes + 1)
    if case .text(_, let rtf, let html)? = ClipClassifier.classify(hugeRich)?.payload {
        check(rtf == nil && html == nil, "oversized rich text stripped")
    } else {
        check(false, "plain text should survive oversized attachments")
    }

    var tooBig = RawPaste()
    tooBig.string = String(repeating: "a", count: Limits.maxTextBytes + 1)
    check(ClipClassifier.classify(tooBig) == nil, "oversized text dropped")

    var flagged = RawPaste()
    flagged.rejectedOversizedText = true
    flagged.imagePNG = Data(count: 32)
    flagged.imageWidth = 4
    flagged.imageHeight = 4
    if case .image(_, _, _)? = ClipClassifier.classify(flagged)?.payload {
        check(true, "oversized text falls back to image")
    } else {
        check(false, "oversized text should keep a real image")
    }
    flagged.imagePNG = nil
    check(ClipClassifier.classify(flagged) == nil, "oversized text without image is dropped")

    var shot = RawPaste()
    shot.imagePNG = Data(count: 20_000)
    shot.imageWidth = 800
    shot.imageHeight = 600
    if case .image(let png, let width, let height)? = ClipClassifier.classify(shot)?.payload {
        check(png.count == 20_000 && width == 800 && height == 600, "screenshot stored")
    } else {
        check(false, "expected image")
    }

    var urlImage = RawPaste()
    urlImage.string = "https://example.com/a.png"
    urlImage.imagePNG = Data(count: 20_000)
    urlImage.imageWidth = 100
    urlImage.imageHeight = 80
    if case .image(_, _, _)? = ClipClassifier.classify(urlImage)?.payload {
        check(true, "url plus image prefers image")
    } else {
        check(false, "expected image for url paste")
    }

    var shortLabel = RawPaste()
    shortLabel.string = "Hi"
    shortLabel.imagePNG = Data(count: 20_000)
    shortLabel.imageWidth = 40
    shortLabel.imageHeight = 40
    if case .image(_, _, _)? = ClipClassifier.classify(shortLabel)?.payload {
        check(true, "short label loses to a real image")
    } else {
        check(false, "expected image")
    }

    var paragraph = RawPaste()
    paragraph.string = "Hello from the notes app today"
    paragraph.imagePNG = Data(count: 20_000)
    paragraph.imageWidth = 40
    paragraph.imageHeight = 40
    if case .text(_, _, _)? = ClipClassifier.classify(paragraph)?.payload {
        check(true, "sentence wins over preview image")
    } else {
        check(false, "expected text")
    }

    var finder = RawPaste()
    finder.string = "Notes.txt"
    finder.filePaths = ["/Users/a/Notes.txt"]
    finder.imagePNG = Data(count: 20_000)
    finder.imageWidth = 32
    finder.imageHeight = 32
    if case .files(let paths)? = ClipClassifier.classify(finder)?.payload {
        check(paths == ["/Users/a/Notes.txt"], "finder file copy stays a file")
    } else {
        check(false, "expected files")
    }

    check(
        ClipClassifier.looksLikeFileList("Notes.txt\nOther.pdf", paths: ["/Users/a/Notes.txt", "/Users/a/Other.pdf"]),
        "multiline file list"
    )
    check(
        !ClipClassifier.looksLikeFileList("hello world this is not a file list really", paths: ["/tmp/a.txt"]),
        "sentence is not a file list"
    )
    check(!ClipClassifier.looksLikeFileList("", paths: ["/tmp/a.txt"]), "empty string is not a file list")

    var filesOnly = RawPaste()
    filesOnly.filePaths = ["/tmp/Report.pdf"]
    if case .files(let paths)? = ClipClassifier.classify(filesOnly)?.payload {
        check(paths == ["/tmp/Report.pdf"], "file url without text")
    } else {
        check(false, "expected a file clip")
    }

    var many = RawPaste()
    many.filePaths = (0..<Limits.maxFiles + 1).map { "/tmp/file-\($0).txt" }
    many.string = many.filePaths
        .map { URL(fileURLWithPath: $0).lastPathComponent }
        .joined(separator: "\n")
    if case .files(let paths)? = ClipClassifier.classify(many)?.payload {
        check(paths.count == Limits.maxFiles, "file list is capped")
        check(paths.first == "/tmp/file-0.txt", "capped list keeps the first files")
    } else {
        check(false, "expected capped files")
    }

    var giantImage = RawPaste()
    giantImage.imagePNG = Data(count: Limits.maxImageBytes + 1)
    giantImage.imageWidth = 10
    giantImage.imageHeight = 10
    check(ClipClassifier.classify(giantImage) == nil, "huge image dropped")

    var zeroImage = RawPaste()
    zeroImage.imagePNG = Data([1, 2, 3])
    zeroImage.imageWidth = 0
    zeroImage.imageHeight = 10
    check(ClipClassifier.classify(zeroImage) == nil, "zero-size image dropped")

    var named = RawPaste()
    named.string = "hello"
    named.sourceApp = "utilBox"
    check(ClipClassifier.classify(named)?.sourceApp == nil, "own app name is not recorded")

    var longSource = RawPaste()
    longSource.string = "hello"
    longSource.sourceApp = String(repeating: "N", count: 120)
    check(ClipClassifier.classify(longSource)?.sourceApp?.count == 80, "source name capped")
}

func testHistory() {
    var history = History()
    let pin = textItem("pinned", pinned: true, at: 1)
    _ = history.insert(pin)
    var firstUnpinned: UUID?
    for index in 0..<Limits.maxUnpinned {
        let id = UUID()
        if index == 0 { firstUnpinned = id }
        _ = history.insert(textItem("u\(index)", id: id, at: Double(10 + index)))
    }
    let overflowID = UUID()
    let evicted = history.insert(textItem("overflow", id: overflowID, at: 10_000))
    check(evicted.contains { $0.id == firstUnpinned }, "oldest unpinned evicted")
    check(history.items.contains { $0.id == pin.id }, "pin kept")
    check(history.items.contains { $0.id == overflowID }, "newest kept")
    check(history.items.contains { $0.id == firstUnpinned } == false, "oldest gone")
    check(history.items.filter { !$0.pinned }.count == Limits.maxUnpinned, "unpinned cap")
    check(history.items.first?.id == pin.id, "pin stays first")
    check(history.items.dropFirst().first?.id == overflowID, "newest unpinned follows pins")

    var order = History()
    let alpha = textItem("a", at: 1)
    let beta = textItem("b", at: 2)
    _ = order.insert(alpha)
    _ = order.insert(beta)
    order.promote(alpha.id, sourceApp: "Notes", now: Date(timeIntervalSince1970: 99))
    check(order.items.first?.id == alpha.id, "promote moves item to top")
    check(order.items.first?.sourceApp == "Notes", "promote updates source")

    var pins = History()
    var pinnedIDs: [UUID] = []
    for index in 0..<Limits.maxPinned {
        let id = UUID()
        pinnedIDs.append(id)
        _ = pins.insert(textItem("p\(index)", id: id, at: Double(index)))
        check(pins.togglePin(id)?.pinned == true, "pin \(index)")
    }
    let extra = UUID()
    _ = pins.insert(textItem("extra", id: extra, at: 10_000))
    check(pins.togglePin(extra) == nil, "pin cap refuses another pin")
    check(pins.items.filter(\.pinned).count == Limits.maxPinned, "pin count unchanged")

    let removed = pins.clearUnpinned()
    check(removed.contains { $0.id == extra }, "clear removes unpinned")
    check(pins.items.allSatisfy(\.pinned), "pins remain")
    check(pins.delete(pinnedIDs[0])?.id == pinnedIDs[0], "delete returns item")
    check(pins.items.contains { $0.id == pinnedIDs[0] } == false, "delete removes item")

    var search = History()
    _ = search.insert(textItem("alpha notes", pinned: true, at: 2, source: "Safari"))
    _ = search.insert(textItem("alphabet soup", at: 3))
    _ = search.insert(textItem("other", at: 4))
    let found = search.filtered(query: "ALP")
    check(found.count == 2, "search is case insensitive")
    check(found.first?.pinned == true, "search keeps pin order")
    check(search.filtered(query: "   ").count == 3, "blank search returns everything")
}

func testDisplay() {
    let now = Date(timeIntervalSince1970: 1_700_000_000)
    check(RelativeTime.string(from: now.addingTimeInterval(-10), now: now) == "Just now", "10s")
    check(RelativeTime.string(from: now.addingTimeInterval(-59), now: now) == "Just now", "59s")
    check(RelativeTime.string(from: now.addingTimeInterval(-60), now: now) == "1m ago", "60s")
    check(RelativeTime.string(from: now.addingTimeInterval(-3599), now: now) == "59m ago", "59m")
    check(RelativeTime.string(from: now.addingTimeInterval(-3600), now: now) == "1h ago", "1h")
    check(RelativeTime.string(from: now.addingTimeInterval(-86_399), now: now) == "23h ago", "23h")
    check(RelativeTime.string(from: now.addingTimeInterval(-86_400), now: now) == "1d ago", "1d")
    check(RelativeTime.string(from: now.addingTimeInterval(-6 * 86_400), now: now) == "6d ago", "6d")
    let older = RelativeTime.string(from: now.addingTimeInterval(-8 * 86_400), now: now)
    check(!older.contains("ago") && !older.isEmpty, "older items use a date, got \(older)")
    check(RelativeTime.string(from: now.addingTimeInterval(30), now: now) == "Just now", "future")

    check(ClipDisplay.flatten("  hello\n\nworld \t there ") == "hello world there", "flatten")
    let long = String(repeating: "ab", count: 250)
    check(ClipDisplay.title(for: textItem(long)).count == 400, "title cap")
    check(ClipDisplay.title(for: textItem("  line\none ")) == "line one", "title flatten")

    let image = ClipItem(
        id: UUID(),
        createdAt: now,
        pinned: false,
        sourceApp: "Preview",
        kind: .image(ImageBody(file: "a.png", width: 800, height: 600, sha256: "abc"))
    )
    let detail = ClipDisplay.detail(for: image, now: now, fileExists: { _ in true })
    check(detail.contains("800×600"), "image size")
    check(detail.contains("Preview"), "image source")
    check(detail.contains("Just now"), "image time")
    check(ClipDisplay.symbolName(for: image) == "photo", "image symbol")
    check(ClipDisplay.tooltip(for: image) == "Image, 800×600", "image tooltip")

    let missing = ClipItem(
        id: UUID(),
        createdAt: now,
        pinned: false,
        sourceApp: nil,
        kind: .files(FileBody(paths: ["/no/such/file.txt"]))
    )
    check(
        ClipDisplay.detail(for: missing, now: now, fileExists: { _ in false }).contains("File missing"),
        "missing file"
    )
    check(ClipDisplay.title(for: missing) == "file.txt", "file title")
    let many = ClipItem(
        id: UUID(),
        createdAt: now,
        pinned: false,
        sourceApp: nil,
        kind: .files(FileBody(paths: ["/tmp/a.txt", "/tmp/b.txt"]))
    )
    check(ClipDisplay.title(for: many) == "2 files", "multi file title")
    check(ClipDisplay.symbolName(for: many) == "doc.on.doc", "multi file symbol")
    check(ClipDisplay.symbolName(for: textItem("hi")) == "doc.text", "text symbol")

    let tip = ClipDisplay.tooltip(for: textItem(String(repeating: "x", count: 600)))
    check(tip.count == 501 && tip.hasSuffix("…"), "tooltip cap")
}

func testStore() throws {
    let directory = FileManager.default.temporaryDirectory
        .appendingPathComponent("utilbox-\(UUID().uuidString)", isDirectory: true)
    defer { try? FileManager.default.removeItem(at: directory) }
    let store = try ClipStore(directory: directory)

    let first = store.ingest(textClip("same"), armedID: nil)
    guard case .inserted(let id) = first else {
        check(false, "first ingest should insert")
        return
    }
    check(store.ingest(textClip("same"), armedID: id) == .ignored, "armed duplicate ignored")
    check(store.items.count == 1, "duplicate does not grow history")

    let other = store.ingest(textClip("other"), armedID: id)
    guard case .inserted = other else {
        check(false, "different text inserts")
        return
    }
    check(store.ingest(textClip("same"), armedID: id) == .ignored, "armed text stays put")
    let promoted = store.ingest(textClip("same"), armedID: nil)
    check(isPromoted(promoted, id), "unarmed duplicate is promoted")
    check(store.items.first?.id == id, "promoted item is first")

    let rtf = Data("{\\rtf1 hello}".utf8)
    let html = Data("<b>hello</b>".utf8)
    let rich = store.ingest(textClip("hello rich", rtf: rtf, html: html, source: "TextEdit"), armedID: nil)
    guard case .inserted(let richID) = rich else {
        check(false, "rich text insert")
        return
    }
    let reopened = try ClipStore(directory: directory)
    guard let richItem = reopened.item(richID), case .text(let body) = richItem.kind else {
        check(false, "rich text reloaded")
        return
    }
    check(body.string == "hello rich", "rich string round trip")
    check(richItem.sourceApp == "TextEdit", "source round trip")
    check(body.rtfFile.flatMap { reopened.blob($0) } == rtf, "rtf round trip")
    check(body.htmlFile.flatMap { reopened.blob($0) } == html, "html round trip")

    let png = [UInt8](1...32)
    let imageA = store.ingest(imageClip(png, width: 8, height: 4), armedID: nil)
    guard case .inserted(let imageID) = imageA else {
        check(false, "image insert")
        return
    }
    check(store.ingest(imageClip(png, width: 8, height: 4), armedID: imageID) == .ignored, "same image ignored")
    let blobCount = (try? FileManager.default.contentsOfDirectory(at: directory.appendingPathComponent("blobs"), includingPropertiesForKeys: nil))?.count ?? -1
    let beforeDelete = blobCount
    store.delete(imageID)
    let afterDelete = (try? FileManager.default.contentsOfDirectory(at: directory.appendingPathComponent("blobs"), includingPropertiesForKeys: nil))?.count ?? -1
    check(afterDelete == beforeDelete - 1, "deleting an image deletes its file (\(beforeDelete) -> \(afterDelete))")
    check(store.item(imageID) == nil, "deleted image is gone")

    let pinnedImage = store.ingest(imageClip([9, 9, 9, 9], width: 3, height: 3), armedID: nil)
    guard case .inserted(let pinnedID) = pinnedImage else {
        check(false, "pinned image insert")
        return
    }
    check(store.togglePin(pinnedID), "pin image")
    let loose = store.ingest(imageClip([8, 8, 8], width: 2, height: 2), armedID: nil)
    guard case .inserted(let looseID) = loose, let looseItem = store.item(looseID), case .image(let looseBody) = looseItem.kind else {
        check(false, "loose image insert")
        return
    }
    store.clearUnpinned()
    check(store.item(pinnedID)?.pinned == true, "clear keeps the pin")
    check(store.item(looseID) == nil, "clear drops unpinned")
    check(store.blob(looseBody.file) == nil, "clear deletes unpinned image bytes")
    if case .image(let body) = store.item(pinnedID)?.kind {
        check(store.blob(body.file) != nil, "pinned image bytes stay")
    } else {
        check(false, "pinned image kind")
    }

    let orphan = directory.appendingPathComponent("blobs").appendingPathComponent("orphan.png")
    try Data("x".utf8).write(to: orphan)
    _ = try ClipStore(directory: directory)
    check(!FileManager.default.fileExists(atPath: orphan.path), "orphan blob removed on open")

    try Data("not json".utf8).write(to: directory.appendingPathComponent("history.json"))
    let recovered = try ClipStore(directory: directory)
    check(recovered.items.isEmpty, "corrupt history starts clean")
    check(
        FileManager.default.fileExists(atPath: directory.appendingPathComponent("history.broken.json").path),
        "corrupt history is kept aside"
    )
    check(store.blob("../secrets") == nil, "blob names cannot escape")
}

func testScratch() throws {
    check(ScratchTitle.from("  \n\t") == "Untitled", "blank scratch title")
    check(ScratchTitle.from("\n  Hello\nworld") == "Hello", "first line is the title")
    let longLine = String(repeating: "ab", count: 50)
    check(ScratchTitle.from(longLine).count == 80, "scratch title cap")

    let directory = FileManager.default.temporaryDirectory
        .appendingPathComponent("utilbox-notes-\(UUID().uuidString)", isDirectory: true)
    defer { try? FileManager.default.removeItem(at: directory) }
    let store = try ScratchStore(directory: directory)

    guard let older = store.create(now: Date(timeIntervalSince1970: 10)),
          let newer = store.create(now: Date(timeIntervalSince1970: 20)) else {
        check(false, "notes should be created")
        return
    }
    check(store.notes.first?.id == newer.id, "newest note is first")
    check(store.selectedID == newer.id, "new note is selected")
    check(older.title == "Untitled", "empty note is untitled")

    let editedAt = Date(timeIntervalSince1970: 30)
    check(store.updateBody(older.id, "alpha notes\nmore", now: editedAt), "edit older note")
    check(store.notes.first?.id == newer.id, "editing does not reorder notes")
    check(store.note(older.id)?.title == "alpha notes", "title follows the edit")
    check(store.note(older.id)?.updatedAt == editedAt, "edit updates the time")
    check(store.updateBody(older.id, "alpha notes\nmore", now: Date(timeIntervalSince1970: 90)), "same text is unchanged")
    check(store.note(older.id)?.updatedAt == editedAt, "unchanged text keeps its time")

    check(store.updateBody(newer.id, "beta"), "edit newer note")
    check(store.filtered(query: "ALP").map(\.id) == [older.id], "search finds the body")
    check(store.filtered(query: "   ").count == 2, "blank search returns every note")

    store.select(older.id)
    store.delete(newer.id)
    check(store.note(newer.id) == nil, "deleted note is gone")
    check(store.selectedID == older.id, "deleting another note keeps the selection")
    store.delete(older.id)
    check(store.notes.isEmpty, "last note can be deleted")
    check(store.selectedID == nil, "nothing is selected after the last delete")

    let order = try ScratchStore(directory: directory.appendingPathComponent("order", isDirectory: true))
    guard let first = order.create(now: Date(timeIntervalSince1970: 1)),
          let middle = order.create(now: Date(timeIntervalSince1970: 2)),
          let newest = order.create(now: Date(timeIntervalSince1970: 3)) else {
        check(false, "order notes should be created")
        return
    }
    order.select(middle.id)
    order.delete(middle.id)
    check(order.selectedID == first.id, "deleting the selected note selects the one that follows")
    order.select(newest.id)
    order.delete(newest.id)
    check(order.selectedID == first.id, "deleting the newest note selects the next one")
    order.delete(first.id)
    check(order.selectedID == nil, "deleting the only remaining note clears the selection")

    guard let kept = store.create() else {
        check(false, "note after delete")
        return
    }
    let limit = String(repeating: "a", count: ScratchStore.maxBodyCharacters)
    check(store.updateBody(kept.id, limit), "body at the limit is kept")
    check(!store.updateBody(kept.id, limit + "b"), "body over the limit is refused")
    check(store.note(kept.id)?.body.count == ScratchStore.maxBodyCharacters, "refused edit leaves the saved text")

    var session = ScratchSession.closed
    session.isOpen = true
    session.window = ScratchFrame(x: 10, y: 20, width: 800, height: 500)
    store.setSession(session)
    let reopened = try ScratchStore(directory: directory)
    check(reopened.notes.count == 1, "notes reload")
    check(reopened.selectedID == kept.id, "selection reloads")
    check(reopened.note(kept.id)?.body == limit, "body reloads")
    check(reopened.session.isOpen, "open scratchpad comes back")
    check(reopened.session.window?.width == 800, "window frame reloads")

    let filled = try ScratchStore(directory: directory.appendingPathComponent("cap", isDirectory: true))
    for _ in 0..<ScratchStore.maxNotes {
        check(filled.create() != nil, "note within the cap")
    }
    check(filled.create() == nil, "note cap refuses another note")
    check(filled.notes.count == ScratchStore.maxNotes, "note count stays at the cap")

    try Data("not json".utf8).write(to: directory.appendingPathComponent("notes.json"))
    let recovered = try ScratchStore(directory: directory)
    check(recovered.notes.isEmpty, "corrupt notes start clean")
    check(recovered.session == .closed, "corrupt notes close the pad")
    check(
        FileManager.default.fileExists(atPath: directory.appendingPathComponent("notes.broken.json").path),
        "corrupt notes are kept aside"
    )
}

func runTests() {
    testSHA256()
    testClassifier()
    testHistory()
    testDisplay()
    do {
        try testStore()
    } catch {
        check(false, "store tests threw \(error)")
    }
    do {
        try testScratch()
    } catch {
        check(false, "scratch tests threw \(error)")
    }
    if log.failed > 0 {
        FileHandle.standardError.write(Data("\(log.failed) failed, \(log.passed) passed\n".utf8))
        exit(1)
    }
    print("All \(log.passed) checks passed")
}

